"""What Module 1 writes besides the tables: copies.fasta and the HTML report.

    python tests/check_report.py WORKDIR DATADIR

Run by run_tests.sh after the single-feature genomes, on their output. Each
copy in copies.fasta must be the reference at the coordinates in its header,
an array must list every unit, and the report must show arrays as arrays.
"""

import csv
import math
import os
import re
import sys


def read_fasta(path):
    seqs, name = {}, None
    with open(path) as f:
        for line in f:
            line = line.strip()
            if line.startswith(">"):
                name = line[1:]
                seqs[name] = []
            elif name is not None:
                seqs[name].append(line)
    return {k: "".join(v) for k, v in seqs.items()}


def check(work, data, genome):
    out = os.path.join(work, genome)
    ref = "".join(read_fasta(os.path.join(data, genome + ".fna")).values())
    copies = read_fasta(os.path.join(out, "copies.fasta"))
    with open(os.path.join(out, "tandem_duplications.tsv")) as f:
        calls = list(csv.DictReader(f, delimiter="\t"))
    with open(os.path.join(out, "tandem_report.html")) as f:
        html = f.read()

    problems = []
    for header, seq in copies.items():
        name, span = header.split()
        start, end = (int(x) for x in span.rsplit(":", 1)[1].split("-"))
        if seq != ref[start - 1:end]:
            problems.append(f"{name} is not the reference at {start}-{end}")
    for i, call in enumerate(calls, 1):
        n = float(call["copy_number"])
        mine = [h for h in copies if h.split(".")[0] == str(i)]
        if len(mine) != math.ceil(n):
            problems.append(f"call {i}: {len(mine)} copies in copies.fasta, copy number {n}")
        if n > 2 and not re.search(r'mechanism-tag[^>]*>array<', html):
            problems.append(f"call {i}: array not shown as one")
    if "Generated by Tandem v0.2" in html:
        problems.append("report footer gives the wrong version")
    return calls, copies, problems


def main(work, data):
    results = []
    for genome, want in (("tandem_2x", 2), ("tandem_3x", 3), ("array_partial_240", None)):
        calls, copies, problems = check(work, data, genome)
        ok = not problems and len(calls) == 1 and (want is None or len(copies) == want)
        detail = problems[0] if problems else f"{len(calls)} call(s), {len(copies)} copies"
        results.append((f"copies.fasta and report, {genome}", ok, detail))

    failed = 0
    for name, ok, detail in results:
        print(f"  {'PASS' if ok else 'FAIL'}  {name:<42} {detail}")
        failed += not ok
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1], sys.argv[2]))
